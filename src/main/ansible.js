'use strict';
/**
 * Export a multi-exec selection as a runnable Ansible bundle.
 *
 * The ad-hoc command you just ran across N hosts and an Ansible playbook
 * describe the same intent; this turns the former into the latter so throwaway
 * work can become something reviewable and repeatable.
 *
 * Teleport hosts reach their nodes through a generated tsh ssh_config, copied
 * into the bundle so it runs standalone.
 */

const fsp = require('fs/promises');
const path = require('path');

/** Quote a scalar for YAML only when it needs it. */
function y(value) {
  const s = String(value ?? '');
  if (s === '') return "''";
  if (/^[A-Za-z0-9_./@-]+$/.test(s)) return s;
  return "'" + s.replace(/'/g, "''") + "'";
}

function slug(s) {
  return String(s || '').replace(/[^A-Za-z0-9_]+/g, '_').replace(/^_+|_+$/g, '') || 'group';
}

/**
 * @param targets [{type, name, alias, hostname, cluster, proxy, login, port, sshConfigPath}]
 * @param command the shell command to run
 */
function build(targets, command, opts = {}) {
  const playName = opts.playName || 'ServerLife multi-exec export';
  const become = !!opts.become;
  const forks = opts.forks || Math.min(20, Math.max(5, targets.length));

  // Group by cluster so each Teleport cluster gets its own ssh_config var.
  const groups = new Map();
  for (const t of targets) {
    const key = t.type === 'teleport' ? 'teleport_' + slug(t.cluster) : 'ssh_hosts';
    if (!groups.has(key)) groups.set(key, { key, type: t.type, cluster: t.cluster, proxy: t.proxy, hosts: [] });
    groups.get(key).hosts.push(t);
  }

  /* ---------- inventory.yml ---------- */
  const lines = ['---', '# Generated by ServerLife', 'all:', '  children:'];
  for (const g of groups.values()) {
    lines.push(`    ${g.key}:`);
    lines.push('      hosts:');
    for (const t of g.hosts) {
      const invName = slug(t.name || t.alias);
      lines.push(`        ${invName}:`);
      if (t.type === 'teleport') {
        // The tsh config maps <node>.<cluster> to a ProxyCommand.
        lines.push(`          ansible_host: ${y(`${t.name}.${t.cluster}`)}`);
      } else {
        lines.push(`          ansible_host: ${y(t.alias)}`);
      }
      if (t.login) lines.push(`          ansible_user: ${y(t.login)}`);
      else if (t.user) lines.push(`          ansible_user: ${y(t.user)}`);
      if (t.type !== 'teleport' && t.port && Number(t.port) !== 22) {
        lines.push(`          ansible_port: ${t.port}`);
      }
    }
    lines.push('      vars:');
    if (g.type === 'teleport') {
      lines.push(`        ansible_port: 3022`);
      lines.push(`        ansible_ssh_common_args: ${y('-F ./ssh_config/' + sshConfigName(g))}`);
    } else {
      // Plain hosts already resolve through the user's own ~/.ssh/config.
      lines.push(`        ansible_ssh_common_args: ${y('-o StrictHostKeyChecking=accept-new')}`);
    }
    lines.push('');
  }
  const inventory = lines.join('\n') + '\n';

  /* ---------- playbook.yml ---------- */
  const indented = String(command).split('\n').map((l) => '          ' + l).join('\n');
  const playbook = [
    '---',
    '# Generated by ServerLife from a multi-exec command.',
    `- name: ${y(playName)}`,
    '  hosts: all',
    '  gather_facts: false',
    become ? '  become: true' : null,
    `  strategy: free`,
    '  tasks:',
    /*
     * `raw`, not `shell`: the command goes over SSH as it is, the way
     * multi-exec ran it, with nothing needed on the host. `shell` ships a
     * Python module across, and current Ansible's modules no longer run on
     * the Python of an older image — Amazon Linux 2's 3.7 fails to parse them
     * — so a `df` that worked in multi-exec came back from the export as
     * "rc=1, command failed" without having run.
     */
    '    - name: Run command',
    '      ansible.builtin.raw: |',
    indented,
    '      register: result',
    '      changed_when: false',
    '      failed_when: false',
    '',
    '    - name: Report',
    '      ansible.builtin.debug:',
    '        msg: "rc={{ result.rc }} {{ result.stdout_lines | default([]) }}"',
    '',
    // What went wrong in its own words: the command's stderr, else Ansible's
    // message (a connection or module failure has no stderr), else the code.
    '    - name: Fail the host if the command failed',
    '      ansible.builtin.fail:',
    '        msg: "{{ (result.stderr | default(\'\') | trim) or (result.msg | default(\'\')) or (\'exited \' ~ result.rc) }}"',
    '      when: result.rc != 0',
    '',
  ].filter((l) => l !== null).join('\n');

  /* ---------- ansible.cfg ---------- */
  const cfg = [
    '# Generated by ServerLife',
    '[defaults]',
    'inventory = ./inventory.yml',
    'host_key_checking = False',
    /*
     * YAML output from Ansible's own callback. `stdout_callback = yaml` named
     * community.general's plugin, which that collection removed in 12.0 —
     * a current install refuses to run at all with it set. ansible-core 2.13
     * and later do the same with the built-in callback; older ones ignore
     * the key and print their usual output.
     */
    'stdout_callback = ansible.builtin.default',
    'callback_result_format = yaml',
    `forks = ${forks}`,
    'interpreter_python = auto_silent',
    '',
    '[ssh_connection]',
    'pipelining = True',
    // No terminal for `raw`: with one, every host prints its login banner
    // (motd, "updates available") ahead of the command's output.
    'usetty = False',
    '',
  ].join('\n');

  /* ---------- run.sh ---------- */
  const run = [
    '#!/usr/bin/env bash',
    '# Generated by ServerLife.',
    'set -euo pipefail',
    'cd "$(dirname "$0")"',
    '',
    '# Teleport hosts need a valid tsh certificate; log in first if needed:',
    '#   tsh login --proxy=<proxy>',
    '',
    'exec ansible-playbook playbook.yml "$@"',
    '',
  ].join('\n');

  const readme = [
    '# ServerLife → Ansible export',
    '',
    `Generated ${new Date().toISOString()}`,
    '',
    `Hosts: ${targets.length}`,
    '',
    '## Run',
    '',
    '```sh',
    './run.sh',
    '# or:',
    'ansible-playbook playbook.yml',
    '```',
    '',
    '## Notes',
    '',
    '- Teleport hosts connect through `ssh_config/`, generated by `tsh config`.',
    '  Those files reference your local `~/.tsh` certificates, so run `tsh login`',
    '  before the playbook if your session has expired.',
    '- Plain SSH hosts resolve through your own `~/.ssh/config`.',
    '- The command runs via `ansible.builtin.raw`: straight over SSH, as',
    '  multi-exec ran it, so it needs nothing on the host — not even Python.',
    '- If it is really a package, service or file change, swap in the matching',
    '  module — that is the point of moving it here. Modules do need Python on',
    '  the host, and current Ansible needs a current one: Amazon Linux 2\'s',
    '  Python 3.7, for one, is too old. Check `python3 --version` there first.',
    '',
  ].join('\n');

  return { inventory, playbook, cfg, run, readme, groups: [...groups.values()] };
}

function sshConfigName(group) {
  return `tsh-${slug(group.cluster || group.proxy)}.conf`;
}

/** Write the bundle to disk, including a copy of each tsh ssh_config. */
async function write(dir, bundle, { teleport } = {}) {
  await fsp.mkdir(dir, { recursive: true });
  await fsp.writeFile(path.join(dir, 'inventory.yml'), bundle.inventory);
  await fsp.writeFile(path.join(dir, 'playbook.yml'), bundle.playbook);
  await fsp.writeFile(path.join(dir, 'ansible.cfg'), bundle.cfg);
  await fsp.writeFile(path.join(dir, 'README.md'), bundle.readme);
  await fsp.writeFile(path.join(dir, 'run.sh'), bundle.run, { mode: 0o755 });

  const written = ['inventory.yml', 'playbook.yml', 'ansible.cfg', 'README.md', 'run.sh'];

  const tpGroups = bundle.groups.filter((g) => g.type === 'teleport');
  if (tpGroups.length && teleport) {
    const cfgDir = path.join(dir, 'ssh_config');
    await fsp.mkdir(cfgDir, { recursive: true });
    for (const g of tpGroups) {
      try {
        const generated = await teleport.writeClusterSshConfig(cfgDir, { proxy: g.proxy, cluster: g.cluster });
        const want = path.join(cfgDir, sshConfigName(g));
        if (generated !== want) await fsp.rename(generated, want);
        written.push('ssh_config/' + sshConfigName(g));
      } catch (e) {
        await fsp.writeFile(
          path.join(cfgDir, sshConfigName(g)),
          `# Could not generate automatically: ${e.message}\n# Run: tsh --proxy=${g.proxy} config > ${sshConfigName(g)}\n`);
        written.push('ssh_config/' + sshConfigName(g) + ' (placeholder)');
      }
    }
  }
  return { dir, files: written };
}

/**
 * A folder name for an export, safe on every platform.
 *
 * It is typed by a person, so it may hold anything: a slash would put the
 * bundle somewhere else entirely, and Windows refuses a further handful of
 * characters and names that end in a dot or a space. Those are dropped or
 * replaced rather than refused, since what was meant is obvious; a name with
 * nothing left falls back to the old default.
 */
function exportFolderName(name) {
  const cleaned = String(name || '')
    // eslint-disable-next-line no-control-regex
    .replace(/[\u0000-\u001f<>:"/\\|?*]+/g, '-')
    .replace(/\s+/g, ' ')
    .replace(/^[\s.-]+|[\s.-]+$/g, '')
    .slice(0, 80)
    .trim();
  if (!cleaned || /^(con|prn|aux|nul|com\d|lpt\d)$/i.test(cleaned)) return 'serverlife-ansible';
  return cleaned;
}

/** A name to suggest: the command's first word, as `ansible-<word>`. */
function suggestFolderName(command) {
  const word = String(command || '').trim().split(/\s+/)[0] || '';
  // Not slug(): that falls back to "group" for an inventory, which is no name
  // for a folder.
  const s = (word.split('/').pop() || '').replace(/[^A-Za-z0-9_-]+/g, '-').replace(/^-+|-+$/g, '');
  return s ? `ansible-${s}` : 'serverlife-ansible';
}

module.exports = { build, write, exportFolderName, suggestFolderName };
